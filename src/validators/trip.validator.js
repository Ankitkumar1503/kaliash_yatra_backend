export const groupPricingItemSchema = z.object({
  minPax: z.coerce.number().int().min(1),
  maxPax: z.coerce.number().int().min(1),
  pricePerPax: z.coerce.number().min(0),
});

import { z } from "zod";

const slugRegex = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export const tripImageSchema = z.object({
  media_id: z.coerce.number().int().positive(),
  alt_text: z.string().nullable().optional(),
  sort_order: z.coerce.number().int().min(0).default(0),
  is_hero: z.boolean().default(false),
});

export const tripItineraryDaySchema = z.object({
  day_number: z.coerce.number().int().positive(),
  title: z.string().trim().min(1, "Day title is required").max(240),
  description: z.string().default(""),
  altitude: z.string().nullable().optional(),
  trekking_time: z.string().nullable().optional(),
  duration: z.string().nullable().optional(),
  accommodation: z.string().nullable().optional(),
  meals: z.string().nullable().optional(),
  media_id: z.coerce.number().int().positive().nullable().optional(),
  image_url: z.string().nullable().optional(),
  imageUrl: z.string().nullable().optional(),
  media_id_2: z.coerce.number().int().positive().nullable().optional(),
  image_url_2: z.string().nullable().optional(),
  imageUrl2: z.string().nullable().optional(),
  sort_order: z.coerce.number().int().min(0).optional(),
});

export const textItemSchema = z.union([
  z.string().trim().min(1),
  z.object({
    text: z.string().trim().min(1),
    sort_order: z.coerce.number().int().min(0).optional(),
  }),
]);

export const tripFaqSchema = z.object({
  question: z.string().trim().min(1, "Question is required"),
  answer: z.string().trim().min(1, "Answer is required"),
  sort_order: z.coerce.number().int().min(0).default(0),
  status: z.enum(["draft", "published", "archived"]).default("published"),
});

export const createTripSchema = z.object({
  title: z.string().trim().min(1, "Title is required").max(240),
  slug: z.string().trim().regex(slugRegex, "Invalid slug format").max(220).optional(),
  code: z.string().trim().max(80).nullable().optional(),
  short_description: z.string().default(""),
  full_description: z.string().default(""),
  destination_id: z.coerce.number().int().positive("A valid destination ID is required"),
  region_id: z.coerce.number().int().positive().nullable().optional(),
  activity_id: z.coerce.number().int().positive().nullable().optional(),
  category_id: z.coerce.number().int().positive().nullable().optional(),
  duration_days: z.coerce.number().int().positive("Duration in days must be at least 1"),
  duration_nights: z.coerce.number().int().min(0).nullable().optional(),
  difficulty: z.enum(["easy", "moderate", "challenging", "strenuous"]).nullable().optional(),
  max_altitude_m: z.coerce.number().int().positive().nullable().optional(),
  max_altitude_label: z.string().nullable().optional(),
  min_group_size: z.coerce.number().int().positive().nullable().optional(),
  max_group_size: z.coerce.number().int().positive().nullable().optional(),
  start_location: z.string().default(""),
  end_location: z.string().default(""),
  best_season: z.string().default(""),
  base_price: z.coerce.number().min(0, "Base price must be greater than or equal to 0"),
  sale_price: z.coerce.number().min(0).nullable().optional(),
  currency: z.string().trim().length(3).regex(/^[A-Z]{3}$/, "Currency must be 3 uppercase letters").default("USD"),
  single_supplement: z.coerce.number().min(0).nullable().optional(),
  child_price: z.coerce.number().min(0).nullable().optional(),
  featured: z.boolean().default(false),
  badge: z.string().max(80).nullable().optional(),
  status: z.enum(["draft", "published", "archived"]).default("draft"),
  published_at: z.string().datetime().nullable().optional(),
  seo_title: z.string().max(240).nullable().optional(),
  seo_description: z.string().nullable().optional(),
  hero_media_id: z.coerce.number().int().positive().nullable().optional(),
  display_area: z.string().nullable().optional(),
  images: z.array(tripImageSchema).optional(),
  itinerary: z.array(tripItineraryDaySchema).optional(),
  highlights: z.array(textItemSchema).optional(),
  inclusions: z.array(textItemSchema).optional(),
  exclusions: z.array(textItemSchema).optional(),
  faqs: z.array(tripFaqSchema).optional(),
    elevation_profile_media_id: z.coerce.number().int().positive().nullable().optional(),
  route_map_media_id: z.coerce.number().int().positive().nullable().optional(),
  video_url: z.string().trim().nullable().optional(),
  departures: z.array(z.any()).optional(),
    elevation_profile_media_id: z.coerce.number().int().positive().nullable().optional(),
  route_map_media_id: z.coerce.number().int().positive().nullable().optional(),
  video_url: z.string().trim().nullable().optional(),
  departures: z.array(z.any()).optional(),
  group_pricing: z.array(groupPricingItemSchema).optional(),
  groupPricing: z.array(groupPricingItemSchema).optional(),
}).strict();

